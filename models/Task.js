const mongoose = require("mongoose");

const TaskSchema = new mongoose.Schema(
  {
    title: { type: String, required: true, trim: true },
    subject: { type: mongoose.Schema.Types.ObjectId, ref: "Subject", required: true },
    topic: { type: mongoose.Schema.Types.ObjectId, ref: "Topic", default: null },
    type: {
      type: String,
      enum: ["lecture", "study", "revision", "practice", "other"],
      default: "study",
    },
    date: { type: Date, required: true }, // the day this task is assigned for
    timeSlot: { type: String, default: "" }, // e.g. "6:00 AM - 8:00 AM"
    targetDurationMinutes: { type: Number, default: 60 },
    actualDurationMinutes: { type: Number, default: 0 },
    status: {
      type: String,
      enum: ["pending", "in-progress", "completed", "missed"],
      default: "pending",
    },
    notes: { type: String, default: "" },
    timerStartedAt: { type: Date, default: null }, // set while a live timer is running
    completedAt: { type: Date, default: null },
    autoGenerated: { type: Boolean, default: false }, // true for auto-created revision tasks
  },
  { timestamps: true }
);

module.exports = mongoose.model("Task", TaskSchema);
